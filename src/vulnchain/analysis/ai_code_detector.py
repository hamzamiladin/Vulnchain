"""
AI-generated code fingerprinting.

Detects code segments likely written by AI tools (GitHub Copilot, Cursor,
ChatGPT, Claude, Gemini, Codeium, Tabnine) using commit metadata, structural
heuristics, security-specific antipatterns, and pattern analysis.

Scoring model (weights sum to 1.0):
  commit_signals    0.30  — AI tool attribution in git metadata
  code_patterns     0.25  — structural markers (TODO, broad catch, over-comment)
  security_apats    0.25  — AI-characteristic security mistakes
  comment_density   0.10  — elevated comment-to-code ratio
  placeholder_strs  0.05  — dummy/placeholder literal values
  method_validity   0.05  — calls to undefined methods (phantom hallucinations)
"""

import logging
import re

from vulnchain.analysis.models import AICodeSegment
from vulnchain.ingestion.models import CommitInfo, SourceFile

logger = logging.getLogger(__name__)

# ── Commit-level signals ──────────────────────────────────────────────────────

_AI_COMMIT_RE = re.compile(
    r"(co-authored-by:\s*(github copilot|cursor|codeium|tabnine|amazon q|"
    r"gemini code assist)|"
    r"generated by (copilot|cursor|chatgpt|claude|gemini|codeium|tabnine|ai)|"
    r"ai-assisted|ai.generated|llm.generated|"
    r"suggested by (copilot|github copilot)|"
    r"\[cursor\]|\[copilot\]|\[ai\])",
    re.IGNORECASE,
)

# Large atomic additions in a single commit to few files (AI dump pattern)
_LARGE_ATOMIC_THRESHOLD = 50  # lines added
_LARGE_ATOMIC_FILE_LIMIT = 2  # max files in that commit

# ── Code-pattern signals ──────────────────────────────────────────────────────

_TODO_RE = re.compile(
    r"(//|#)\s*(TODO|FIXME):\s*(add error handling|implement|TODO|placeholder|stub|"
    r"handle this|not implemented|fill in|complete this|add validation|add logging)",
    re.IGNORECASE,
)

_BROAD_CATCH_RE = re.compile(
    # C-family: catch(Exception ...) / catch(Error ...) / catch(Throwable ...)
    r"catch\s*\(\s*(Exception|Error|Throwable|BaseException)\s*[\w]*\s*\)"
    r"|"
    # Python: bare except or except Exception
    r"^\s*except\s*(?:Exception|BaseException)?(?:\s+as\s+\w+)?\s*:\s*(?:pass|#.*)?$",
    re.IGNORECASE | re.MULTILINE,
)

_GENERIC_VAR_RE = re.compile(
    # Only flag when used as an assignment target (= on same line),
    # and only single-word names (not result_set, response_data, etc.)
    r"\b(result|response|data|temp|obj|value|item)\s*=",
    re.IGNORECASE,
)

_OVER_COMMENT_RE = re.compile(
    r"(//|#)\s+(?:This (?:method|function|code|class|endpoint|handler)\s+|"
    r"The following\s+|We (?:first|then|next|finally)\s+|"
    r"This will\s+|Here we\s+|Note that\s+|This is a\s+|"
    r"This (?:ensures|checks|validates|handles|creates|returns|initializes)\s+)",
    re.IGNORECASE,
)

# ── Security antipattern signals (highly specific to AI tools) ────────────────

_SSL_VERIFY_DISABLED_RE = re.compile(
    r"verify\s*=\s*False"
    r"|InsecureSkipVerify\s*(?::|=)\s*true"
    r"|ssl\._create_unverified_context\s*\(\s*\)"
    r"|check_hostname\s*=\s*False"
    r"|VERIFY_SSL\s*=\s*False"
    r"|SSL_VERIFY\s*=\s*False",
    re.IGNORECASE,
)

# Placeholder/example secret values that AI tools produce in examples
_PLACEHOLDER_SECRET_RE = re.compile(
    r"""['"]("""
    r"""your[-_]?(?:secret|api[-_]?key|token|password|key|access[-_]?key|private[-_]?key)|"""
    r"""changeme|change[-_]me|change_this|"""
    r"""password123|pass(?:word)?123|admin123|secret123|test[-_]?(?:key|secret|token)|"""
    r"""my[-_]?(?:secret|password|key|token)|"""
    r"""supersecretkey|verysecretkey|hardcoded[-_]?secret|"""
    r"""insert[-_]?(?:your|api|secret)|replace[-_]?(?:with|me)|"""
    r"""todo[-_]?(?:replace|insert|fill)|placeholder[-_]?(?:key|secret|token)"""
    r""")['"]\s*""",
    re.IGNORECASE,
)

# AI uses SHA-256/MD5 for password hashing instead of bcrypt/argon2
_WEAK_PASSWORD_HASH_RE = re.compile(
    r"hashlib\.(md5|sha1|sha256|sha512)\s*\(\s*(?:password|passwd|pwd|pass)\b",
    re.IGNORECASE,
)

# JWT without signature verification — AI frequently produces this
_JWT_NO_VERIFY_RE = re.compile(
    r"""algorithms\s*=\s*\[["']none["']\]"""
    r"""|verify_signature['":\s]*False"""
    r"""|options\s*=\s*\{[^}]*verify_signature['":\s]*False"""
    r"""|jwt\.decode\s*\([^)]*,\s*None\s*[,)]""",
    re.IGNORECASE,
)

# Timing attack: token comparison with == (AI misses constant-time compare)
_TIMING_UNSAFE_COMPARE_RE = re.compile(
    r"\b(?:token|secret|hmac|signature|hash|digest)\b[^=\n]*==\s*"
    r"|==\s*[^=\n]*\b(?:token|secret|hmac|signature|hash|digest)\b",
    re.IGNORECASE,
)

# ── Placeholder literal strings ───────────────────────────────────────────────

_PLACEHOLDER_LITERAL_RE = re.compile(
    r"""['"](?:"""
    r"""example\.com|http://localhost(?::\d+)?(?:/[^\s'"]*)?|"""
    r"""0\.0\.0\.0|127\.0\.0\.1|"""
    r"""dummy[-_]?(?:key|secret|token|data|value|user|password|url)|"""
    r"""test[-_]?(?:user|admin|value|data)|"""
    r"""admin(?:@example\.com)?|"""
    r"""foo|bar|baz|qux|foobar|"""
    r"""xxx+|aaa+|zzz+"""
    r""")['"]\s*""",
    re.IGNORECASE,
)

# ── Comment-density helpers ───────────────────────────────────────────────────

